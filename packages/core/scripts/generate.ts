// Turns the repository's manifest and taxonomy into src/data.ts and copies the
// WebP icons and the license files into the package. Runs before every build.

import { cp, readFile, rm, writeFile } from "node:fs/promises"
import path from "node:path"

const root = path.resolve(import.meta.dir, "../../..")
const pkg = path.resolve(import.meta.dir, "..")

const manifest: { style: number; sizes: { webp: number[] }; icons: Record<string, { file: string }> } =
  JSON.parse(await readFile(path.join(root, "manifest.json"), "utf8"))
const taxonomy: { release: string; commit: string; parents: Record<string, string[]>; names: Record<string, Record<string, string>> } =
  JSON.parse(await readFile(path.join(root, "taxonomy.json"), "utf8"))
const { version } = JSON.parse(await readFile(path.join(pkg, "package.json"), "utf8"))

const files = Object.fromEntries(Object.entries(manifest.icons).map(([id, { file }]) => [id, file]))
const json = (value: unknown) => JSON.stringify(value)

await writeFile(
  path.join(pkg, "src/data.ts"),
  `// Generated by scripts/generate.ts from manifest.json and taxonomy.json: do not edit.
export const VERSION = ${json(version)}
export const STYLE = ${manifest.style}
export const SIZES = ${json(manifest.sizes.webp)} as const
export const TAXONOMY_RELEASE = ${json(taxonomy.release)}
export const TAXONOMY_COMMIT = ${json(taxonomy.commit)}
/** File name of each id that has its own icon. */
export const FILES: Readonly<Record<string, string>> = ${json(files)}
/** Parents of every Open Food Facts taxonomy entry. Open Food Facts data, ODbL 1.0. */
export const PARENTS: Readonly<Record<string, readonly string[]>> = ${json(taxonomy.parents)}
/** English and French names of the ids that have an icon. Open Food Facts data, ODbL 1.0. */
export const NAMES: Readonly<Record<string, { en?: string; fr?: string }>> = ${json(taxonomy.names)}
`,
)

await rm(path.join(pkg, "icons"), { recursive: true, force: true })
await cp(path.join(root, "icons/webp"), path.join(pkg, "icons/webp"), { recursive: true })
for (const file of ["LICENSE", "LICENSE-ICONS", "NOTICE"]) await cp(path.join(root, file), path.join(pkg, file))

console.log(`${Object.keys(files).length} icons, ${Object.keys(taxonomy.parents).length} taxonomy entries`)
